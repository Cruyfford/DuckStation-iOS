#!/usr/bin/env python3
"""Generates ARMSX2Bridge+Stubs.mm: default implementations for every ARMSX2Bridge method
that DuckStation's bridge (DSBridge.mm) doesn't implement by hand.

The ARMSX2 SwiftUI frontend talks to the emulator only through ARMSX2Bridge.h. PS2-only
features (texture packs, pnach patches, DEV9, ...) get harmless defaults here.

Usage: gen_bridge_stubs.py <ARMSX2Bridge.h> <DSBridge.mm> <output.mm>
"""

import re
import sys


def strip_macro(text: str, name: str) -> str:
    """Removes NAME(...) including nested parentheses."""
    while True:
        i = text.find(name + "(")
        if i < 0:
            return text
        depth, j = 0, i + len(name)
        while j < len(text):
            if text[j] == "(":
                depth += 1
            elif text[j] == ")":
                depth -= 1
                if depth == 0:
                    break
            j += 1
        text = text[:i].rstrip() + text[j + 1:]


def selector_of(decl: str) -> str:
    """'+ (void)setFoo:(int)a bar:(int)b' -> 'setFoo:bar:'"""
    body = re.sub(r"^[-+]\s*\([^)]*\)\s*", "", decl.strip())
    parts = re.findall(r"([A-Za-z_][A-Za-z0-9_]*)\s*:", body)
    if parts:
        return "".join(p + ":" for p in parts)
    return body.split()[0]


def default_body(ret: str) -> str:
    r = ret.replace("nonnull", "").replace("nullable", "").replace("_Nonnull", "").replace("_Nullable", "").strip()
    nullable = "nullable" in ret
    if r == "void":
        return ""
    if r in ("BOOL",):
        return "return NO;"
    if r in ("int", "NSInteger", "NSUInteger", "float", "double", "uint32_t", "NSTimeInterval"):
        return "return 0;"
    if nullable:
        return "return nil;"
    if r.startswith("NSString"):
        return 'return @"";'
    if r.startswith("NSArray"):
        return "return @[];"
    if r.startswith("NSDictionary"):
        return "return @{};"
    if r.startswith("NSData"):
        return "return [NSData data];"
    if r.startswith("UIView"):
        return "return [[UIView alloc] initWithFrame:CGRectZero];"
    return "return nil;"


def completion_calls(decl: str) -> str:
    """Call completion blocks so Swift callers never hang waiting on a stub."""
    calls = []
    for m in re.finditer(r":\s*\(\s*(nullable\s+|nonnull\s+)?([A-Za-z0-9_]+)\s*\)\s*([A-Za-z_][A-Za-z0-9_]*)", decl):
        btype, name = m.group(2), m.group(3)
        if btype == "ARMSX2SaveStateCompletion":
            calls.append(f"if ({name}) dispatch_async(dispatch_get_main_queue(), ^{{ {name}(NO); }});")
        elif btype == "ARMSX2TemporaryStateCreationCompletion":
            calls.append(f"if ({name}) dispatch_async(dispatch_get_main_queue(), ^{{ {name}(nil); }});")
        elif btype == "ARMSX2RetroAchievementsCompletion":
            calls.append(
                f'if ({name}) dispatch_async(dispatch_get_main_queue(), ^{{ {name}(NO, @"Not available in DuckStation"); }});')
    return " ".join(calls)


def main():
    header_path, impl_path, out_path = sys.argv[1:4]
    header = open(header_path, encoding="utf-8").read()
    impl = open(impl_path, encoding="utf-8").read()

    implemented = set()
    for m in re.finditer(r"^[-+]\s*\([^)]*\)[^{;]*\{", impl, re.M):
        implemented.add(selector_of(m.group(0).rstrip("{")))

    out = [
        "// GENERATED by scripts/ios/gen_bridge_stubs.py - do not edit.",
        "// Default implementations for ARMSX2Bridge methods DuckStation doesn't provide (PS2-only features).",
        "",
        '#import "ARMSX2Bridge.h"',
        "",
        "#if !__has_feature(objc_arc)",
        "#error This file must be compiled with ARC.",
        "#endif",
        "",
        "#pragma clang diagnostic ignored \"-Wobjc-protocol-method-implementation\"",
        "",
    ]

    count = 0
    for m in re.finditer(r"@interface\s+ARMSX2Bridge\s*(\(\s*(\w+)\s*\))?(.*?)@end", header, re.S):
        category = m.group(2) or "Core"
        body = m.group(3)
        decls = re.findall(r"^\s*([-+]\s*\(.*?\).*?);", body, re.M | re.S)
        methods = []
        for d in decls:
            d = re.sub(r"\s+", " ", d).strip()
            for macro in ("NS_SWIFT_NAME", "API_AVAILABLE", "API_UNAVAILABLE", "NS_SWIFT_UNAVAILABLE"):
                d = strip_macro(d, macro)
            d = re.sub(r"\s*NS_REFINED_FOR_SWIFT", "", d).strip()
            sel = selector_of(d)
            if sel in implemented:
                continue
            ret = re.match(r"[-+]\s*\(([^)]*)\)", d).group(1)
            methods.append(f"{d} {{ {completion_calls(d)} {default_body(ret)} }}".replace("  ", " "))
        if not methods:
            continue
        out.append(f"@implementation ARMSX2Bridge (DSStubs{category})")
        out.extend(methods)
        out.append("@end")
        out.append("")
        count += len(methods)

    open(out_path, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(f"generated {count} stub(s); {len(implemented)} implemented by hand")


if __name__ == "__main__":
    main()
